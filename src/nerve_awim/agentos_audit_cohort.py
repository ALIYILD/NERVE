def _source(ident, kind, fields, *, at=1000, model=MODEL, provider=PROVIDER, parents=()):
    return dict(id=ident,kind=kind,model=model,provider=provider,observed_at=at,
                derived_from=list(parents),fields=fields)


def _citation(ident, *fields):
    # Source IDs and the evidence fields to cite are explicitly authored per case.
    return dict(source_id=ident,fields=sorted(['model','provider','observed_at']+
                                            ['fields.'+field for field in fields]))


def _case(ident, family, kind, sources, decision, citations):
    claim=dict(kind=kind,model=MODEL,provider=PROVIDER,at=1000,max_age=100)
    if kind=='execution_success':
        claim['request_id']='target-request'
    return dict(id=ident,family=family,bundle=dict(schema=SCHEMA,simulated=True,claim=claim,sources=sources),
                expected=dict(decision=decision,citations=sorted(citations,key=lambda row:row['source_id'])))


