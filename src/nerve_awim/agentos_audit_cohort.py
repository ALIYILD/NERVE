def canonical_identity(row):
    """Conservative semantic identity ignoring incidental names, order and text.

    Preserve target-vs-other identities, applicability windows, values and nested
    provenance structure. Positive prices normalize to paid, timestamps to their
    freshness class. Thus renaming IDs/labels or changing irrelevant prose cannot
    turn an already-used composition into fresh evidence.
    """
    from .agentos_audit_evidence import validate_bundle
    bundle=validate_bundle(row['bundle'])
    claim=bundle['claim']
    sources={source['id']:source for source in bundle['sources']}
    memo={}
    def normalized(ident):
        if ident in memo:
            return memo[ident]
        source=sources[ident]
        at=source['observed_at']
        freshness='stale' if at<claim['at']-claim['max_age'] else 'future' if at>claim['at'] else 'fresh'
        fields={}
        for key,value in source['fields'].items():
            if key=='text':
                fields[key]='assertion-text'
            elif key=='request_id':
                fields[key]='target' if value==claim.get('request_id') else 'other'
            elif key in ('input_usd','output_usd'):
                fields[key]='zero' if value==0 else 'paid'
            else:
                fields[key]=value
        record=dict(kind=source['kind'],model='target' if source['model']==claim['model'] else 'other',
                    provider='target' if source['provider']==claim['provider'] else 'other',
                    freshness=freshness,fields=fields,
                    parents=sorted([sha256(_encode(normalized(parent)).encode()).hexdigest()
                                    for parent in source['derived_from']]))
        memo[ident]=record
        return record
    value=dict(kind=claim['kind'],sources=sorted([normalized(ident) for ident in sources],key=_encode))
    return sha256(_encode(value).encode()).hexdigest()


def _encode(value):
    return json.dumps(value,sort_keys=True,separators=(',',':'),allow_nan=False)


def validate_cohort(value=None):
    """Reject malformed gold, split reuse, and equivalence to public controls."""
    from .agentos_audit_evidence import expected_decision
    from .agentos_audit_fixtures import development_cases
    value=cohort() if value is None else value
    if (type(value) is not dict or set(value)!={'scope','id','limitation','splits'}
            or value['scope']!=SCOPE or value['id']!=COHORT_ID or value['limitation']!=LIMITATION):
        raise ValueError('exact cohort metadata required')
    counts={'train':2,'selection':4,'retention':4,'final':6}
    if type(value['splits']) is not dict or set(value['splits'])!=set(counts):
        raise ValueError('exact cohort splits required')
    prior={canonical_identity(row) for row in development_cases()}
    ids,families,identities=set(),set(),set()
    for phase,count in counts.items():
        if type(value['splits'][phase]) is not list or len(value['splits'][phase])!=count:
            raise ValueError('wrong split size: '+phase)
        for row in value['splits'][phase]:
            if (type(row) is not dict or set(row)!={'id','family','bundle','expected'}
                    or any(type(row[key]) is not str or not 1<=len(row[key])<=128 for key in ('id','family'))):
                raise ValueError('exact case fields required')
            identity=canonical_identity(row)
            if row['id'] in ids or row['family'] in families or identity in identities or identity in prior:
                raise ValueError('duplicate or reused audit composition')
            if expected_decision(row['bundle'])!=row['expected']:
                raise ValueError('hand-authored gold disagrees with oracle: '+row['id'])
            ids.add(row['id']); families.add(row['family']); identities.add(identity)
    return value


